const DICTS: Record<UiLang, Dict> = { fr, en };
let lang: UiLang = 'fr';

export function setLang(l: UiLang) {
  lang = l;
  document.documentElement.lang = l;
}
export function getLang(): UiLang {
  return lang;
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function fmtNumber(n: number, digits = 0): string {
  return n.toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-GB', { maximumFractionDigits: digits, minimumFractionDigits: 0 });
}

export function fmtDate(ts: number): string {
  return new Date(ts).toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
}

export function fmtCm(cm: number): string {
  return lang === 'fr' ? `${fmtNumber(cm, 1)} cm` : `${fmtNumber(cm, 1)} cm (${fmtNumber(cm / 2.54, 1)} in)`;
}

export function fmtMeters(m: number): string {
  return m < 1 ? `${fmtNumber(m * 100)} cm` : `${fmtNumber(m, m < 10 ? 1 : 0)} m`;
}

